#!/usr/bin/env python3
"""Generate rask_sdk/_generated from the API v3 contract.

Standard library only, on purpose: the output is a pure function of contract/openapi.json. `--check` fails when the
committed files have drifted from the contract, and CI runs it.

What it reads from the contract:
- x-rask-open-enum and every other response enum become `Union[Literal[...], str]`, so unknown values survive (SDK-1);
  requests use the closed `<Name>Known` Literal (DESIGN 4.2).
- oneOf + discriminator becomes a callable pydantic discriminator with an UnknownVariant fallback (SDK-1).
- Idempotency-Key is optional in every signature whatever the contract says: the SDK fills it in (SDK-12).
- deprecated: true on an operation adds typing_extensions.deprecated (S14).

Generate from a copy with `--contract copy.json --out some/dir`.
"""

from __future__ import annotations

import argparse
import difflib
import json
import keyword
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# Generated by tools/generate.py from contract/openapi.json. Do not edit by hand.\n"
HTTP_METHODS = ("get", "post", "put", "patch", "delete")

# Attribute names a pydantic model cannot use as field names, plus the SDK's own members on RaskModel.
RESERVED_FIELDS = {
    "copy", "dict", "json", "construct", "parse_obj", "parse_raw", "parse_file", "from_orm", "schema", "schema_json",
    "update_forward_refs", "validate", "http", "to_dict",
}  # fmt: skip
RESERVED_PARAMS = {
    "self", "body", "options", "idempotency_key", "if_match", "if_none_match", "timeout",
    "extra_headers", "extra_query", "extra_body",
}  # fmt: skip


def literal(values: list[Any]) -> str:
    """The inside of a Literal[...]: JSON strings stay readable, True stays Python."""
    return ", ".join(
        json.dumps(value) if isinstance(value, str) else repr(value) for value in values if value is not None
    )


def snake(name: str) -> str:
    """createVoiceClone -> create_voice_clone, Voice clones -> voice_clones."""
    name = re.sub(r"[\s\-]+", "_", name)
    name = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def camel(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[\s_\-]+", name) if part)


def py_name(name: str) -> str:
    return f"{name}_" if keyword.iskeyword(name) else name


def first_paragraph(text: str | None, limit: int = 0) -> str:
    if not text:
        return ""
    paragraph = text.strip().split("\n\n")[0]
    paragraph = " ".join(line.strip() for line in paragraph.splitlines())
    if limit and len(paragraph) > limit:
        paragraph = paragraph[: limit - 3].rstrip() + "..."
    return paragraph


def escape_doc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', "'''")


def wrap(text: str, indent: str, width: int = 118) -> list[str]:
    lines: list[str] = []
    current = ""
    for word in text.split():
        if current and len(indent) + len(current) + 1 + len(word) > width:
            lines.append(indent + current)
            current = word
        else:
            current = f"{current} {word}" if current else word
    if current:
        lines.append(indent + current)
    return lines


def docstring(text: str, indent: str) -> list[str]:
    text = escape_doc(text).strip()
    if not text:
        return []
    if text.endswith('"'):
        text += " "
    body = wrap(text, indent)
    if len(body) == 1 and len(body[0]) + 6 <= 118:
        return [f'{indent}"""{text}"""']
    return [f'{indent}"""', *body, f'{indent}"""']


@dataclass
class Param:
    wire: str
    name: str
    type: str
    required: bool
    doc: str = ""


@dataclass
class Op:
    id: str
    resource: str
    name: str
    http_method: str
    path: str
    summary: str
    description: str
    deprecated: bool
    path_params: list[Param] = field(default_factory=list)
    query_params: list[Param] = field(default_factory=list)
    body_params: list[Param] = field(default_factory=list)
    body_mode: str = "none"  # none, flat or root
    body_required: bool = False
    root_body_type: str = ""
    idempotency: str = "none"
    if_match: str = "none"
    if_none_match: bool = False
    response: str | None = None
    success: list[int] = field(default_factory=list)
    paginated: bool = False
    item_type: str = ""


class Contract:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: dict[str, Any] = spec["components"]["schemas"]
        self.inline_models: dict[str, Any] = {}
        self.inline_params: dict[str, Any] = {}
        self.request_refs: set[str] = set()

    def deref(self, node: dict[str, Any]) -> dict[str, Any]:
        while "$ref" in node:
            target: Any = self.spec
            for part in node["$ref"].split("/")[1:]:
                target = target[part]
            node = target
        return node

    @staticmethod
    def ref_name(node: dict[str, Any]) -> str:
        return str(node["$ref"]).split("/")[-1]

    def is_enum(self, name: str) -> bool:
        return "enum" in self.schemas[name]

    def is_union(self, name: str) -> bool:
        return "oneOf" in self.schemas[name]

    def is_map(self, name: str) -> bool:
        schema = self.schemas[name]
        return schema.get("type") == "object" and "properties" not in schema

    # --- Response types: open everywhere, never closed by the SDK.

    def response_type(self, schema: dict[str, Any], owner: str) -> str:
        if "$ref" in schema:
            return self.ref_name(schema)
        if "anyOf" in schema:
            branches = [branch for branch in schema["anyOf"] if branch.get("type") != "null"]
            if len(branches) != 1:
                raise SystemExit(f"{owner}: anyOf other than [X, null] is not supported: {schema}")
            inner = self.response_type(branches[0], owner)
            nullable = len(branches) != len(schema["anyOf"])
            return f"Optional[{inner}]" if nullable else inner
        if "oneOf" in schema:
            raise SystemExit(f"{owner}: an inline oneOf needs a named schema")
        kind = schema.get("type")
        if isinstance(kind, list):
            others = [item for item in kind if item != "null"]
            if len(others) != 1:
                raise SystemExit(f"{owner}: type list {kind} is not supported")
            inner = self.response_type({**schema, "type": others[0]}, owner)
            return f"Optional[{inner}]" if "null" in kind else inner
        if "enum" in schema or "const" in schema:
            values = schema.get("enum", [schema.get("const")])
            if all(isinstance(value, str) for value in values if value is not None):
                return f"Union[Literal[{literal(values)}], str]"
            return self.response_type(
                {key: item for key, item in schema.items() if key not in ("enum", "const")}, owner
            )
        if kind == "string":
            fmt = str(schema.get("format"))
            return {"date-time": "_dt.datetime", "date": "_dt.date"}.get(fmt, "str")
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"List[{self.response_type(schema.get('items', {}), owner)}]"
        if kind == "object" or "properties" in schema or "additionalProperties" in schema:
            if schema.get("properties"):
                name = owner
                self.inline_models[name] = schema
                return name
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Dict[str, {self.response_type(extra, owner + 'Value')}]"
            return "Dict[str, Any]"
        if not schema or set(schema) <= {"description", "title", "default", "example"}:
            return "Any"
        raise SystemExit(f"{owner}: schema not supported: {schema}")

    # --- Request types: closed enums, TypedDicts for nested objects, null never sent.

    def request_type(self, schema: dict[str, Any], owner: str) -> str:
        if "$ref" in schema:
            name = self.ref_name(schema)
            if self.is_enum(name):
                return f"_m.{name}Known"
            if self.is_map(name):
                return self.request_type({**self.schemas[name], "description": ""}, name)
            self.mark_request(name)
            return f"{name}Param"
        if "anyOf" in schema:
            branches = [branch for branch in schema["anyOf"] if branch.get("type") != "null"]
            if len(branches) != 1:
                raise SystemExit(f"{owner}: anyOf other than [X, null] is not supported: {schema}")
            return self.request_type(branches[0], owner)
        kind = schema.get("type")
        if isinstance(kind, list):
            others = [item for item in kind if item != "null"]
            return self.request_type({**schema, "type": others[0]}, owner)
        if "enum" in schema or "const" in schema:
            return f"Literal[{literal(schema.get('enum', [schema.get('const')]))}]"
        if kind == "string":
            fmt = str(schema.get("format"))
            return {"date-time": "Union[str, _dt.datetime]", "date": "Union[str, _dt.date]"}.get(fmt, "str")
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            return f"Sequence[{self.request_type(schema.get('items', {}), owner)}]"
        if kind == "object":
            if schema.get("properties"):
                self.inline_params[owner] = schema
                return f"{owner}Param"
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                return f"Mapping[str, {self.request_type(extra, owner + 'Value')}]"
            return "Mapping[str, Any]"
        if not schema or set(schema) <= {"description", "title", "default", "example"}:
            return "Any"
        raise SystemExit(f"{owner}: request schema not supported: {schema}")

    def mark_request(self, name: str) -> None:
        if name in self.request_refs:
            return
        self.request_refs.add(name)
        schema = self.schemas[name]
        for wire, child in schema.get("properties", {}).items():
            self.request_type(child, f"{name}{camel(wire)}")
        for branch in schema.get("oneOf", []):
            self.request_type(branch, name)


def collect_operations(contract: Contract) -> list[Op]:
    spec = contract.spec
    operations: list[Op] = []
    for path, item in spec["paths"].items():
        for http_method in HTTP_METHODS:
            raw = item.get(http_method)
            if raw is None:
                continue
            operation_id = raw["operationId"]
            tags = raw.get("tags") or ["Default"]
            op = Op(
                id=operation_id,
                resource=snake(tags[0]),
                name=snake(operation_id),
                http_method=http_method.upper(),
                path=path,
                summary=raw.get("summary", ""),
                description=raw.get("description", ""),
                deprecated=bool(raw.get("deprecated")),
            )
            for raw_param in raw.get("parameters", []):
                param = contract.deref(raw_param)
                location, wire = param["in"], param["name"]
                doc = first_paragraph(param.get("description"), 160)
                if location == "header":
                    lowered = wire.lower()
                    if lowered == "idempotency-key":
                        op.idempotency = "required" if param.get("required") else "optional"
                    elif lowered == "if-match":
                        op.if_match = "required" if param.get("required") else "optional"
                    elif lowered == "if-none-match":
                        op.if_none_match = True
                    else:
                        raise SystemExit(f"{operation_id}: header parameter {wire} is not supported")
                    continue
                target = op.path_params if location == "path" else op.query_params
                name = py_name(wire)
                if name in RESERVED_PARAMS:
                    raise SystemExit(f"{operation_id}: parameter {wire} clashes with an SDK option")
                owner = f"{camel(operation_id)}{camel(wire)}"
                schema = param.get("schema", {})
                type_text = "int" if contract.deref(schema).get("type") == "integer" else "str"
                if location == "query":
                    type_text = contract.request_type(schema, owner)
                target.append(Param(wire, name, type_text, bool(param.get("required")), doc))

            body = raw.get("requestBody")
            if body:
                body = contract.deref(body)
                op.body_required = bool(body.get("required"))
                schema_ref = body["content"]["application/json"]["schema"]
                schema = contract.deref(schema_ref)
                if "oneOf" in schema:
                    op.body_mode = "root"
                    op.root_body_type = contract.request_type(schema_ref, camel(operation_id))
                else:
                    op.body_mode = "flat"
                    required = set(schema.get("required", []))
                    taken = {param.name for param in op.path_params + op.query_params} | RESERVED_PARAMS
                    for wire, prop in schema.get("properties", {}).items():
                        name = py_name(wire)
                        if name in taken:
                            raise SystemExit(f"{operation_id}: body field {wire} clashes with another parameter")
                        owner = f"{camel(operation_id)}{camel(wire)}"
                        op.body_params.append(
                            Param(
                                wire,
                                name,
                                contract.request_type(prop, owner),
                                wire in required,
                                first_paragraph(prop.get("description"), 160),
                            )
                        )

            for code, raw_response in raw["responses"].items():
                if not code.startswith("2"):
                    continue
                op.success.append(int(code))
                response = contract.deref(raw_response)
                content = response.get("content", {}).get("application/json")
                if content:
                    if "$ref" not in content["schema"]:
                        raise SystemExit(f"{operation_id}: the JSON response must be a named schema")
                    op.response = contract.ref_name(content["schema"])

            extension = raw.get("x-rask-operation", {})
            op.paginated = extension.get("pagination") == "cursor"
            if op.paginated:
                data = contract.deref({"$ref": f"#/components/schemas/{op.response}"})["properties"]["data"]
                op.item_type = "_m." + contract.response_type(data["items"], op.response or "")
            operations.append(op)
    return operations


# --- models.py


def emit_model_class(contract: Contract, name: str, schema: dict[str, Any], lines: list[str]) -> None:
    lines.append(f"class {name}(RaskModel):")
    doc = docstring(first_paragraph(schema.get("description")), "    ")
    lines.extend(doc)
    required = set(schema.get("required", []))
    wrote = bool(doc)
    for wire, prop in schema.get("properties", {}).items():
        attr = py_name(wire)
        alias = None
        if attr != wire or attr in RESERVED_FIELDS or attr.startswith("model_") or attr.startswith("_"):
            attr = f"{wire.lstrip('_')}_"
            alias = wire
        type_text = contract.response_type(prop, f"{name}{camel(wire)}")
        if wire in required:
            line = f"    {attr}: {type_text}"
            if alias:
                line += f' = Field(alias="{alias}")'
        else:
            if not type_text.startswith("Optional["):
                type_text = f"Optional[{type_text}]"
            line = f"    {attr}: {type_text} = None"
            if alias:
                line = f'    {attr}: {type_text} = Field(default=None, alias="{alias}")'
        lines.append(line)
        description = first_paragraph(prop.get("description"), 200) or first_paragraph(
            contract.deref(prop).get("description"), 200
        )
        lines.extend(docstring(description, "    "))
        wrote = True
    if not wrote:
        lines.append("    pass")
    lines.append("")
    lines.append("")


def emit_models(contract: Contract) -> str:
    schemas = contract.schemas
    lines = [
        HEADER.rstrip(),
        '"""Response models. Open by design: unknown enum values, union variants and fields never fail (S12)."""',
        "",
        "from __future__ import annotations",
        "",
        "import datetime as _dt",
        "from typing import Annotated, Any, Dict, List, Literal, Optional, Union",
        "",
        "from pydantic import Discriminator, Field, Tag",
        "",
        "from .._models import UNKNOWN_TAG, RaskModel, UnknownVariant, discriminate",
        "",
    ]
    names: list[str] = []

    lines.append(
        "# Enums: <Name>Known is what this SDK version knows and what requests take; <Name> is what responses hold."
    )
    for name, schema in schemas.items():
        if "enum" not in schema:
            continue
        lines.append(f"{name}Known = Literal[{literal(schema['enum'])}]")
        lines.append(f"{name} = Union[{name}Known, str]")
        names += [name, f"{name}Known"]
    lines.append("")
    lines.append("")

    objects = {
        name: schema
        for name, schema in schemas.items()
        if "enum" not in schema and "oneOf" not in schema and not contract.is_map(name)
    }
    for name, schema in objects.items():
        emit_model_class(contract, name, schema, lines)
        names.append(name)
    # Inline objects with properties get a class named after their owner. Emitting one can reveal another.
    done: set[str] = set()
    while set(contract.inline_models) - done:
        for name in sorted(set(contract.inline_models) - done):
            emit_model_class(contract, name, contract.inline_models[name], lines)
            names.append(name)
            done.add(name)

    for name in schemas:
        if contract.is_map(name) and "enum" not in schemas[name]:
            lines.append(f"{name} = {contract.response_type({**schemas[name], 'description': ''}, name)}")
            names.append(name)
    lines.append("")

    for name, schema in schemas.items():
        if "oneOf" not in schema:
            continue
        discriminator = schema["discriminator"]
        mapping = {value: contract.ref_name({"$ref": target}) for value, target in discriminator["mapping"].items()}
        doc = first_paragraph(schema.get("description"))
        if doc:
            lines.append(f"# {name}: {doc}")
        lines.append(f"{name} = Annotated[")
        lines.append("    Union[")
        seen: list[str] = []
        for branch in schema["oneOf"]:
            variant = contract.ref_name(branch)
            if variant not in seen:
                seen.append(variant)
                lines.append(f'        Annotated[{variant}, Tag("{variant}")],')
        lines.append("        Annotated[UnknownVariant, Tag(UNKNOWN_TAG)],")
        lines.append("    ],")
        mapping_text = json.dumps(mapping)
        lines.append(f'    Discriminator(discriminate("{discriminator["propertyName"]}", {mapping_text})),')
        lines.append("]")
        names.append(name)
    lines.append("")
    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for name in sorted(set(names)))
    lines.append('    "UnknownVariant",')
    lines.append("]")
    return "\n".join(lines) + "\n"


# --- params.py


def emit_typed_dict(contract: Contract, name: str, schema: dict[str, Any], lines: list[str]) -> None:
    required = set(schema.get("required", []))
    lines.append(f"class {name}Param(TypedDict, total=False):")
    lines.extend(docstring(first_paragraph(schema.get("description")), "    "))
    wrote = bool(schema.get("description"))
    for wire, prop in schema.get("properties", {}).items():
        type_text = contract.request_type(prop, f"{name}{camel(wire)}")
        if wire in required:
            type_text = f"Required[{type_text}]"
        lines.append(f"    {wire}: {type_text}")
        lines.extend(docstring(first_paragraph(prop.get("description"), 200), "    "))
        wrote = True
    if not wrote:
        lines.append("    pass")
    lines.append("")
    lines.append("")


def emit_params(contract: Contract) -> str:
    lines = [
        HEADER.rstrip(),
        '"""Nested request objects, as plain dicts. Enums here are closed: requests send what the contract lists."""',
        "",
        "from __future__ import annotations",
        "",
        "import datetime as _dt",
        "from collections.abc import Mapping, Sequence",
        "from typing import Any, Literal, Required, TypedDict, Union",
        "",
        "from . import models as _m",
        "",
    ]
    done: set[str] = set()
    names: list[str] = []
    # A nested object can reveal further ones, so keep going until nothing new shows up.
    while True:
        pending = sorted(
            name
            for name in contract.request_refs - done
            if "oneOf" not in contract.schemas[name] and "enum" not in contract.schemas[name]
        )
        inline = sorted(set(contract.inline_params) - done)
        if not pending and not inline:
            break
        for name in pending:
            emit_typed_dict(contract, name, contract.schemas[name], lines)
            done.add(name)
            names.append(f"{name}Param")
        for name in inline:
            emit_typed_dict(contract, name, contract.inline_params[name], lines)
            done.add(name)
            names.append(f"{name}Param")
    for name in sorted(contract.request_refs):
        schema = contract.schemas[name]
        if "oneOf" in schema:
            variants = ", ".join(f"{contract.ref_name(branch)}Param" for branch in schema["oneOf"])
            lines.append(
                f"{name}Param = Union[{variants}]" if len(schema["oneOf"]) > 1 else f"{name}Param = {variants}"
            )
            names.append(f"{name}Param")
    lines.append("")
    lines.append("__all__ = [")
    lines.extend(f'    "{name}",' for name in sorted(set(names)))
    lines.append("]")
    return "\n".join(lines) + "\n"


# --- operations.py


def emit_operations(operations: list[Op]) -> str:
    lines = [
        HEADER.rstrip(),
        '"""What the runtime needs to know about each operation, taken from the contract."""',
        "",
        "from __future__ import annotations",
        "",
        "from .._operation import Operation",
        "",
    ]
    for op in operations:
        query = tuple((param.wire, param.name) for param in op.query_params)
        body = tuple((param.wire, param.name) for param in op.body_params)
        lines.append(f"{op.id} = Operation(")
        lines.append(f"    id={op.id!r},")
        lines.append(f"    resource={op.resource!r},")
        lines.append(f"    method_name={op.name!r},")
        lines.append(f"    http_method={op.http_method!r},")
        lines.append(f"    path={op.path!r},")
        lines.append(f"    path_params={tuple(param.wire for param in op.path_params)!r},")
        lines.append(f"    query_params={query!r},")
        lines.append(f"    body_mode={op.body_mode!r},")
        lines.append(f"    body_required={op.body_required!r},")
        lines.append(f"    body_params={body!r},")
        lines.append(f"    idempotency={op.idempotency!r},")
        lines.append(f"    if_match={op.if_match!r},")
        lines.append(f"    if_none_match={op.if_none_match!r},")
        lines.append(f"    response={op.response!r},")
        lines.append(f"    success={tuple(op.success)!r},")
        lines.append(f"    paginated={op.paginated!r},")
        lines.append(f"    deprecated={op.deprecated!r},")
        lines.append(")")
    lines.append("")
    lines.append("OPERATIONS: dict[str, Operation] = {")
    lines.extend(f"    {op.id!r}: {op.id}," for op in operations)
    lines.append("}")
    return "\n".join(lines) + "\n"


# --- resources.py


def result_type(op: Op, mode: str) -> str:
    if op.paginated:
        return f"{'AsyncPage' if mode == 'async' else 'Page'}[{op.item_type}]"
    if op.response is None:
        return "NoContent"
    return f"_m.{op.response}"


def signature_lines(op: Op, *, if_none_match_type: str | None = None) -> list[str]:
    positional = [f"{param.name}: {param.type}" for param in op.path_params]
    keyword_only: list[str] = []
    if op.if_match == "required":
        keyword_only.append("if_match: str")
    if op.body_mode == "root":
        root = f"body: _p.{op.root_body_type}"
        keyword_only.append(root if op.body_required else f"body: Optional[_p.{op.root_body_type}] = None")
    required = [param for param in op.query_params + op.body_params if param.required]
    optional = [param for param in op.query_params + op.body_params if not param.required]
    keyword_only += [f"{param.name}: {qualify(param.type)}" for param in required]
    keyword_only += [f"{param.name}: Optional[{qualify(param.type)}] = None" for param in optional]
    if op.if_match == "optional":
        keyword_only.append("if_match: Optional[str] = None")
    if op.idempotency != "none":
        keyword_only.append("idempotency_key: Optional[str] = None")
    if op.if_none_match:
        keyword_only.append(if_none_match_type or "if_none_match: Optional[str] = None")
    lines = ["self,", *[f"{item}," for item in positional]]
    if keyword_only:
        lines.append("*,")
        lines.extend(f"{item}," for item in keyword_only)
    lines.append("**options: Unpack[RequestOptions],")
    return lines


def qualify(type_text: str) -> str:
    """Point the Param TypedDicts of a generated type expression at the params module."""
    return re.sub(r"(?<![\w.])([A-Z]\w*Param)\b", r"_p.\1", type_text)


def method_doc(op: Op) -> list[str]:
    lines: list[str] = []
    title = escape_doc(op.summary.strip() or op.id)
    if title.endswith('"'):
        title += " "
    lines.append(f'        """{title}')
    paragraph = first_paragraph(op.description)
    if paragraph and paragraph != op.summary.strip():
        lines.append("")
        lines.extend(wrap(escape_doc(paragraph), "        "))
    documented = [param for param in op.query_params + op.body_params if param.doc]
    if documented:
        lines.append("")
        lines.append("        Args:")
        for param in documented:
            lines.extend(wrap(escape_doc(f"{param.name}: {param.doc}"), "            "))
    lines.append('        """')
    return lines


def call_lines(op: Op, mode: str) -> list[str]:
    arguments = [f"_ops.{op.id}"]
    if not op.paginated:
        arguments.append(f"_m.{op.response}" if op.response else "NoContent")
    else:
        arguments.append(f"_m.{op.response}")
    if op.path_params:
        pairs = ", ".join(f'"{param.wire}": {param.name}' for param in op.path_params)
        arguments.append(f"path={{{pairs}}}")
    if op.query_params:
        pairs = ", ".join(f'"{param.wire}": {param.name}' for param in op.query_params)
        arguments.append(f"query={{{pairs}}}")
    if op.body_mode == "flat":
        pairs = ", ".join(f'"{param.wire}": {param.name}' for param in op.body_params)
        arguments.append(f"body={{{pairs}}}")
    elif op.body_mode == "root":
        arguments.append("body=body")
    if op.if_match != "none":
        arguments.append("if_match=if_match")
    if op.if_none_match:
        arguments.append("if_none_match=if_none_match")
    if op.idempotency != "none":
        arguments.append("idempotency_key=idempotency_key")
    arguments.append("options=options")
    function = "_list" if op.paginated else "_call"
    prefix = "return await " if mode == "async" else "return "
    lines = [f"        {prefix}self.{function}("]
    lines.extend(f"            {argument}," for argument in arguments)
    lines.append("        )")
    return lines


def emit_method(op: Op, mode: str) -> list[str]:
    lines: list[str] = []
    prefix = "async def" if mode == "async" else "def"
    result = result_type(op, mode)
    if op.if_none_match:
        for marker, returned in (
            ("if_none_match: None = None", result),
            ("if_none_match: str", f"Union[{result}, NotModified]"),
        ):
            lines.append("    @overload")
            lines.append(f"    {prefix} {op.name}(")
            lines.extend(f"        {item}" for item in signature_lines(op, if_none_match_type=marker))
            lines.append(f"    ) -> {returned}: ...")
            lines.append("")
        result = f"Union[{result}, NotModified]"
    if op.deprecated:
        message = json.dumps(f"{op.id} is deprecated in the Rask API. See the migration guide.")
        lines.append(f"    @deprecated({message})")
    lines.append(f"    {prefix} {op.name}(")
    lines.extend(f"        {item}" for item in signature_lines(op))
    lines.append(f"    ) -> {result}:")
    lines.extend(method_doc(op))
    lines.extend(call_lines(op, mode))
    lines.append("")
    return lines


def emit_resources(operations: list[Op]) -> str:
    groups: dict[str, list[Op]] = {}
    for op in operations:
        groups.setdefault(op.resource, []).append(op)
    lines = [
        HEADER.rstrip(),
        '"""Every operation, grouped by the contract\'s tag and named after its operationId."""',
        "",
        "from __future__ import annotations",
        "",
        "import datetime as _dt",
        "from collections.abc import Mapping, Sequence",
        "from typing import Any, Literal, Optional, Union, overload",
        "",
        "from typing_extensions import Unpack, deprecated",
        "",
        "from .._helpers import AsyncJobsHelpers, AsyncUploadsHelpers, SyncJobsHelpers, SyncUploadsHelpers",
        "from .._models import NoContent, NotModified",
        "from .._operation import RequestOptions",
        "from .._pagination import AsyncPage, Page",
        "from .._resource import AsyncResource, SyncResource",
        "from . import models as _m",
        "from . import operations as _ops",
        "from . import params as _p",
        "",
        "",
    ]
    helpers = {"jobs": "JobsHelpers", "uploads": "UploadsHelpers"}
    for mode, base, prefix in (("sync", "SyncResource", ""), ("async", "AsyncResource", "Async")):
        for resource, ops in groups.items():
            class_name = f"{prefix}{camel(resource)}"
            helper = helpers.get(resource)
            bases = base if not helper else f"{'Async' if mode == 'async' else 'Sync'}{helper}, {base}"
            lines.append(f"class {class_name}({bases}):")
            lines.append(f'    """{camel(resource)} operations."""')
            lines.append("")
            for op in ops:
                lines.extend(emit_method(op, mode))
            lines.append("")
        mixin = "AsyncResources" if mode == "async" else "SyncResources"
        lines.append(f"class {mixin}:")
        lines.append('    """The client attributes, one per resource."""')
        lines.append("")
        for resource in groups:
            lines.append(f"    {resource}: {prefix}{camel(resource)}")
        lines.append("")
        lines.append("    def _init_resources(self) -> None:")
        for resource in groups:
            lines.append(f"        self.{resource} = {prefix}{camel(resource)}(self)")
        lines.append("")
        lines.append("")
    lines.append('__all__ = ["AsyncResources", "SyncResources"]')
    return "\n".join(lines) + "\n"


def generate(spec: dict[str, Any]) -> dict[str, str]:
    contract = Contract(spec)
    operations = collect_operations(contract)
    # Order matters: operations reveal the request schemas, models reveal the inline response classes.
    models = emit_models(contract)
    params = emit_params(contract)
    return {
        "__init__.py": HEADER,
        "models.py": models,
        "params.py": params,
        "operations.py": emit_operations(operations),
        "resources.py": emit_resources(operations),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--contract", type=Path, default=ROOT / "contract" / "openapi.json")
    parser.add_argument("--out", type=Path, default=ROOT / "rask_sdk" / "_generated")
    parser.add_argument("--check", action="store_true", help="Fail if the committed files differ; write nothing.")
    args = parser.parse_args(argv)

    spec = json.loads(args.contract.read_text(encoding="utf-8"))
    files = generate(spec)
    if args.check:
        drift = 0
        for name, text in files.items():
            target = args.out / name
            current = target.read_text(encoding="utf-8") if target.exists() else ""
            if current != text:
                drift += 1
                print(f"{target} differs from the contract:", file=sys.stderr)
                diff = difflib.unified_diff(current.splitlines(), text.splitlines(), lineterm="", n=1)
                for number, line in enumerate(diff):
                    if number == 20:
                        print("  ...", file=sys.stderr)
                        break
                    print(f"  {line}", file=sys.stderr)
        if drift:
            print("Run: python tools/generate.py", file=sys.stderr)
        return 1 if drift else 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (args.out / name).write_text(text, encoding="utf-8")
    operation_count = sum(1 for path in spec["paths"].values() for method in HTTP_METHODS if method in path)
    print(f"Generated {len(files)} files, {operation_count} operations, into {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
